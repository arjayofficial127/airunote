import assert from 'node:assert/strict';
import { initialPanes, addLensPane, freezeLens, panesSchema } from '../components/notes/panes';
import { destinationKey, rememberDestinations, openDestination, closeDestination, reorderDestination } from '../components/notes/destinations';
let state = rememberDestinations(initialPanes('root'));
const template = state.lenses[0]!;
const open = (key: string, viewId: string) => { state = openDestination(state, key, { ...template, viewId }); };
open('calendar', 'calendar');
state = rememberDestinations({ ...state, lenses: state.lenses.map(p => ({ ...p, date: '2026-10-24', period: 'month', calendarDisplay: 'agenda' })) });
open('plan', 'agenda'); open('calendar', 'calendar');
assert.equal(state.destinations.filter(x => x.key === 'calendar').length, 1);
assert.equal(state.lenses[0]!.date, '2026-10-24'); assert.equal(state.lenses[0]!.period, 'month'); assert.equal(state.lenses[0]!.calendarDisplay, 'agenda');
assert.equal(state.lenses.length, 1, 'Opening tabs does not add panes');
open('collection:one', 'collection:one');
state = rememberDestinations({ ...state, lenses: state.lenses.map(p => ({ ...p, collectionPageId: 'page-13' })) });
open('collection:two', 'collection:two'); open('collection:one', 'collection:one');
assert.equal(state.lenses[0]!.collectionPageId, 'page-13');
assert.equal(state.destinations.filter(x => x.key.startsWith('collection:')).length, 2, 'Books have independent identities');
state = reorderDestination(state, 'collection:one', -1);
const saved = panesSchema.parse(JSON.parse(JSON.stringify(state)));
assert.deepEqual(saved, JSON.parse(JSON.stringify(state)), 'Tabs, order, page and context survive validated preferences');
state = freezeLens(state, state.lenses[0]!.id);
const frozen = state;
open('plan', 'agenda'); assert.deepEqual(state, frozen, 'All-frozen panes stay unchanged');
state = rememberDestinations(addLensPane(state, 'side-by-side', 'root', 'box'));
open('plan', 'agenda'); assert.equal(state.lenses.length, 2); assert.equal(state.lenses[0]!.viewId, 'collection:one');
open('collection:one', 'collection:one'); assert.equal(state.activeLens, state.lenses[0]!.id, 'Reopening a visible frozen resource focuses its existing pane');
state = closeDestination(state, 'collection:one', 'root'); assert.equal(state.lenses.length, 1); assert.equal(state.destinations.some(t => t.key === 'collection:one'), false);
while (state.destinations.length) state = closeDestination(state, state.destinations[0]!.key, 'root');
assert.equal(state.destinationsClosed, true); open('plan', 'agenda'); assert.equal(state.destinationsClosed, false); assert.equal(destinationKey(state.lenses[0]!), 'plan');
const legacy = rememberDestinations({ ...initialPanes('root'), lenses: [{ ...template, viewId: 'calendar' }, { ...template, id: 'copy', viewId: 'calendar' }] });
assert.equal(legacy.lenses.filter(p => p.viewId === 'calendar').length, 1, 'Legacy duplicated calendars migrate to one tool');
console.log('Destination identity, context, page, ordering, persistence, close, Freeze and legacy migration checks passed');
