import assert from 'node:assert/strict';
import { addFolderPane, followFolder, freezeLens, initialPanes, panesSchema, removeFolderPane } from '../components/notes/panes';
let state = initialPanes('root');
for (let index = 2; index <= 6; index++) state = addFolderPane(state, `folder-${index}`);
assert.equal(state.folders.length, 4);
state = followFolder(state, 'folder-2', 'source', 'calendar');
state = freezeLens(state, 'lens-2');
state = followFolder(state, 'folder-3', 'destination', 'board-1');
assert.equal(state.lenses[0]?.folderId, 'source', 'Frozen folder context must not follow navigation');
assert.equal(state.lenses[0]?.viewId, 'calendar');
assert.equal(state.lenses[1]?.folderId, 'destination');
assert.equal(state.folders.find(pane => pane.id === 'folder-2')?.folderId, 'source', 'Folder panes navigate independently');
for (let index = 3; index <= 6; index++) state = freezeLens(state, `lens-${index}`);
assert.equal(state.lenses.length, 4);
assert.equal(state.lenses.filter(pane => !pane.frozen).length, 1);
assert.equal(state.lenses[3]?.frozen, false);
state = { ...state, lenses: state.lenses.filter((_, index) => index !== 1) };
state = freezeLens(state, 'replacement');
assert.equal(state.lenses.length, 4, 'Closing a frozen pane makes room for another freeze');
for (const pane of [...state.folders]) state = removeFolderPane(state, pane.id);
assert.equal(state.folders.length, 1);
assert.equal(state.activeFolder, state.folders[0]?.id);
assert.equal(state.lenses.find(pane => !pane.frozen)?.folderId, state.folders[0]?.folderId, 'Following stays connected when the active folder pane closes');
assert.equal(panesSchema.safeParse(state).success, true);
assert.equal(panesSchema.safeParse({ ...state, lenses: state.lenses.map(pane => ({ ...pane, frozen: true })) }).success, false);
assert.equal(panesSchema.safeParse({ ...state, folders: [] }).success, false);
assert.equal(panesSchema.safeParse({ ...state, lenses: [state.lenses[3], state.lenses[3]] }).success, false);
console.log('Pane state: independent navigation, freeze order, limits, close recovery and preference validation passed.');
