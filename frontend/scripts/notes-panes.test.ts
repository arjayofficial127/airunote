import assert from 'node:assert/strict';
import { addFolderPane, addLensPane, followFolder, freezeLens, initialPanes, panesSchema, removeFolderPane, removeLensPane, unfreezeLens } from '../components/notes/panes';
let state = initialPanes('root');
for (let index = 2; index <= 6; index++) state = addFolderPane(state, `folder-${index}`);
assert.equal(state.folders.length, 4);
state = followFolder(state, 'folder-2', 'source', 'calendar');
state = { ...state, lensWidth: 900 };
const original = state.lenses[0]!;
state = freezeLens(state, original.id);
assert.equal(state.lenses.length, 1, 'Freeze must never create a pane');
assert.equal(state.lensWidth, 900, 'Freeze must preserve saved width');
assert.deepEqual(state.lenses[0], { ...original, frozen: true }, 'Freeze preserves the current view and controls');
state = followFolder(state, 'folder-3', 'destination', 'board-1');
assert.equal(state.lenses.length, 1, 'Navigation with all views frozen must not create a following pane');
assert.equal(state.lenses[0]?.folderId, 'source');
assert.equal(state.lenses[0]?.viewId, 'calendar');
assert.equal(state.folders.find(pane => pane.id === 'folder-2')?.folderId, 'source', 'Space panes navigate independently');
assert.equal(panesSchema.safeParse(JSON.parse(JSON.stringify(state))).success, true, 'All-frozen preferences survive reload');
state = addLensPane(state, 'lens-2', 'destination', 'board-1');
assert.equal(state.lenses[0]?.frozen, true);
assert.equal(state.lenses[1]?.folderId, 'destination');
assert.equal(state.lenses[1]?.frozen, false);
assert.equal(panesSchema.safeParse(state).success, true, 'Legacy frozen-then-following preferences remain valid');
state = { ...state, lensWidth: 1000 };
state = unfreezeLens(state, original.id, 'destination', 'board-1');
assert.equal(state.lenses.length, 2);
assert.equal(state.lenses[0]?.folderId, 'destination', 'Unfreeze catches up to the selected Space');
assert.equal(state.lensWidth, 1000);
assert.equal(panesSchema.safeParse(state).success, true, 'Multiple following panes are valid');
state = followFolder(state, 'folder-3', 'next', 'list');
assert.ok(state.lenses.every(pane => pane.folderId === 'next'));
state = freezeLens(state, 'lens-2');
state = removeLensPane(state, original.id);
assert.equal(state.lenses[0]?.frozen, true, 'Closing the following pane does not silently unfreeze another');
assert.equal(removeLensPane(state, 'lens-2'), state, 'The final view cannot be removed');
for (let index = 3; index <= 6; index++) state = addLensPane(state, `lens-${index}`, 'next', 'list');
assert.equal(state.lenses.length, 4);
const allFrozen = { ...state, lenses: state.lenses.map(pane => ({ ...pane, frozen: true })) };
assert.equal(panesSchema.safeParse(allFrozen).success, true);
state = removeLensPane(state, 'lens-3');
state = addLensPane(state, 'replacement', 'next', 'list');
assert.equal(state.lenses.length, 4, 'Closing a view makes room for an explicit new pane');
for (const pane of [...state.folders]) state = removeFolderPane(state, pane.id);
assert.equal(state.folders.length, 1);
assert.equal(state.activeFolder, state.folders[0]?.id);
assert.equal(state.lenses.find(pane => !pane.frozen)?.folderId, state.folders[0]?.folderId);
assert.equal(panesSchema.safeParse(state).success, true);
assert.equal(panesSchema.safeParse({ ...state, folders: [] }).success, false);
assert.equal(panesSchema.safeParse({ ...state, lenses: [state.lenses[0], state.lenses[0]] }).success, false);
console.log('Pane state: independent Freeze/Unfreeze, explicit creation, width preservation, all-frozen navigation, limits, close recovery and legacy preference compatibility passed.');
